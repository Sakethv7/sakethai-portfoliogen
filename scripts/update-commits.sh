#!/bin/sh
# Rewrites src/data/commits.ts with commits per month for the last 12 months.
# Needs the GitHub CLI, logged in. Counts public repositories only unless private contributions are enabled on the profile.
set -e
python3 - <<'PY'
import json, subprocess
from datetime import date

today = date.today()
months = []
y, m = today.year, today.month
for _ in range(12):
    months.append((y, m))
    m -= 1
    if m == 0:
        y, m = y - 1, 12
months.reverse()

def span(y, m):
    ny, nm = (y + 1, 1) if m == 12 else (y, m + 1)
    return f"{y}-{m:02d}-01T00:00:00Z", f"{ny}-{nm:02d}-01T00:00:00Z"

fields = []
for i, (y, m) in enumerate(months):
    a, b = span(y, m)
    fields.append(f'm{i}: contributionsCollection(from: "{a}", to: "{b}") {{ totalCommitContributions restrictedContributionsCount }}')
query = "query { viewer { " + " ".join(fields) + " } }"
out = json.loads(subprocess.check_output(["gh", "api", "graphql", "-f", f"query={query}"]))["data"]["viewer"]
rows = [(f"{y}-{m:02d}", out[f"m{i}"]["totalCommitContributions"]) for i, (y, m) in enumerate(months)]
restricted = sum(out[f"m{i}"]["restrictedContributionsCount"] for i in range(12))
body = "// Generated by scripts/update-commits.sh. Do not edit by hand.\n"
body += f"export const commitsAsOf = '{today.isoformat()}';\n"
body += f"export const commitsIncludePrivate = {str(restricted > 0).lower()};\n"
body += "export const commitsPerMonth: [string, number][] = [\n" + "".join(f"  ['{k}', {v}],\n" for k, v in rows) + "];\n"
open("src/data/commits.ts", "w").write(body)
print(body)
PY
